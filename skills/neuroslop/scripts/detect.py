def strip_code(text):
    """Заменяет код пробелами той же длины, чтобы номера строк не съехали."""
    def blank(m):
        return re.sub(r"[^\n]", " ", m.group(0))
    text = re.sub(r"(?ms)^(```|~~~).*?^\1[^\n]*$", blank, text)
    text = re.sub(r"`[^`\n]+`", blank, text)
    text = re.sub(r"(?m)^(\s{4,}|\t).*$", blank, text)  # отступы-код
    text = re.sub(r"https?://\S+", blank, text)
    text = re.sub(r"(?s)^---\n.*?\n---\n", blank, text)  # frontmatter
    return text


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def snippet(text, start, end, pad=40):
    s = max(0, start - pad)
    e = min(len(text), end + pad)
    return re.sub(r"\s+", " ", text[s:e]).strip()


def norm(word):
    return word.lower().replace("ё", "е")


def classify(word):
    """'prtf' — причастие, 'grnd' — деепричастие, None — прочее."""
    w = norm(word)
    if MORPH is not None:
        if not MORPH.word_is_known(w):
            return None
        for p in MORPH.parse(w)[:2]:
            if p.score < 0.2:
                continue
            if "GRND" in p.tag and w not in GERUND_STOP:
                return "grnd"
            if "PRTF" in p.tag:
                base = p.inflect({"sing", "masc", "nomn"})
                if norm(base.word if base else w) not in PARTICIPLE_STOP:
                    return "prtf"
                return None
        return None
    if w in GERUND_STOP:
        return None
    if re.fullmatch(r"\w{3,}(?:ущ|ющ|ащ|ящ|вш)(?:ий|ая|ее|ие|его|ей|ему|им|ую|ими|их|ем|ой|ийся|аяся|ееся|иеся|егося|ейся|имся|уюся|ихся)", w):
        return None if any(w.startswith(s[:-2]) for s in PARTICIPLE_STOP) else "prtf"
    if re.fullmatch(r"\w{3,}(?:уя|юя|ивая|ывая|вая|уясь|юясь|аясь|яясь|ясь|вшись|ав|ив|ыв|ев)", w) and not w.endswith(("тив", "хив", "лив", "рав", "тав", "нев", "ров")):
        return "grnd"
    return None


def analyze(raw):
    text = strip_code(raw)
    hits = defaultdict(list)

    for cat, pat, hint in PATTERNS:
        for m in re.finditer(pat, text, flags=re.IGNORECASE | re.MULTILINE):
            lead = len(m.group(0)) - len(re.sub(r"^[\s.!?]+", "", m.group(0)))
            hits[cat].append({"line": line_of(text, m.start() + lead), "match": m.group(0).strip(" \n.!?"), "hint": hint,
                              "context": snippet(text, m.start(), m.end())})

    # Тире
    dashes = list(DASH_RE.finditer(text))
    for m in dashes:
        line_start = text.rfind("\n", 0, m.start()) + 1
        before = text[line_start:m.start()]
        after = text[m.end():m.end() + 25]
        if re.fullmatch(r"\s*(?:[-*+]|\d+\.)?\s*\*\*[^*]+\*\*:?\s*", before) or re.fullmatch(r"\s*(?:[-*+]|\d+\.)\s*\S{1,30}\s*", before):
            kind, hint = "термин", "термин — определение в списке: норма для справочника, оставь"
        elif re.match(r"(?:это|так\s+это)\b", after, re.I):
            kind, hint = "это-связка", "«X — это Y»: часто можно без «это» или перестроить; в цепочке подряд — слоп"
        elif re.match(r"(?:и|а|но|ведь|причём|причем|зато|потому|именно|то\s+есть|включая)\b", after, re.I):
            kind, hint = "драма", "тире-пауза перед «и/а/но» для драматизма: замени запятой или точкой"
        elif re.search(r",\s*$", text[max(0, m.start() - 1):m.start() + 1]) or re.search(r"(?:^|[.!?]\s+)(?:Если|Когда|Чтобы|Раз)\b[^.!?]*$", text[max(0, m.start() - 150):m.start()]):
            kind, hint = "условие", "«Если X — Y»: разговорно; в тексте лучше запятая или «то»"
        else:
            kind, hint = "прочее", "проверь: подлежащее и сказуемое-существительное без связки? это норма; иначе двоеточие, запятая или точка"
        hits["тире"].append({"line": line_of(text, m.start()), "match": f"— [{kind}]", "hint": hint,
                             "context": snippet(text, m.start(), m.end()), "kind": kind})
    hits["тире"].sort(key=lambda h: ["драма", "это-связка", "условие", "прочее", "термин"].index(h["kind"]))

    # Обороты: причастия/деепричастия, сгруппированные по предложениям
    prose = re.sub(r"(?m)^\s*(?:#+|[-*+]|\d+\.|>|\|).*$", lambda m: m.group(0), text)
    sentences = []
    pos = 0
    for para in re.split(r"\n\s*\n", prose):
        for s in SENT_SPLIT.split(para):
            idx = text.find(s, pos)
            sentences.append((idx if idx >= 0 else pos, s))
            if idx >= 0:
                pos = idx + len(s)
    words_total = 0
    sent_lengths = []
    nominalizations = 0
    for start, s in sentences:
        words = re.findall(rf"{W}+(?:-{W}+)?", s)
        if not words:
            continue
        words_total += len(words)
        sent_lengths.append(len(words))
        nominalizations += sum(1 for w in words if re.search(r"(?:ание|ение|ация|ости|ание|ений|аний|ации)$", norm(w)) and len(w) > 6)
        kinds = Counter()
        found = []
        for w in words:
            k = classify(w)
            # Причастие считаем оборотом, только если оно стоит после запятой
            # (постпозиция: «…, являющаяся основой»); «защищённых веток» — не оборот.
            if k == "prtf" and not re.search(rf",\s+(?:(?!(?:что|и|а|но|как|когда|если|где|чтобы|то|или|в|на|из|для|с)\s){W}+\s+)?{re.escape(w)}\b", s, re.I):
                k = None
            if k:
                kinds[k] += 1
                found.append(w)
        if kinds:
            label = "деепричастие" if kinds["grnd"] and not kinds["prtf"] else "причастие" if kinds["prtf"] and not kinds["grnd"] else "причастие+деепричастие"
            heavy = sum(kinds.values()) >= 2 or kinds["grnd"] and re.search(r",\s*\w+(?:я|в|ясь|вшись)\b[^,]*[.!?]?\s*$", s)
            hits["обороты"].append({"line": line_of(text, max(start, 0)), "match": ", ".join(found),
                                    "hint": f"{label}{' (несколько в одном предложении / хвостовой оборот)' if heavy else ''}: раздели на два предложения или замени глаголом",
                                    "context": re.sub(r"\s+", " ", s).strip()[:220], "heavy": bool(heavy)})

    stats = {
        "слов": words_total,
        "тире_всего": len(dashes),
        "тире_подозрительных_на_1000_слов": round(sum(1 for h in hits["тире"] if h["kind"] in SUSPECT_DASH) * 1000 / words_total, 1) if words_total else 0,
        "оборотов_на_1000_слов": round(len(hits["обороты"]) * 1000 / words_total, 1) if words_total else 0,
        "отглаг_сущ_на_100_слов": round(nominalizations * 100 / words_total, 1) if words_total else 0,
        "средняя_длина_предложения": round(statistics.mean(sent_lengths), 1) if sent_lengths else 0,
        "разброс_длины_предложений_cv": round(statistics.pstdev(sent_lengths) / statistics.mean(sent_lengths), 2) if len(sent_lengths) > 2 else None,
        "морфология": "pymorphy3" if MORPH else "суффиксы (pipx install pymorphy3 для точности)",
    }
    return stats, hits


def report(name, stats, hits):
    out = [f"# {name}", ""]
    out.append("Статистика: " + "; ".join(f"{k}={v}" for k, v in stats.items()))
    flags = []
    if stats["тире_подозрительных_на_1000_слов"] > 5:
        flags.append(f"много тире-пауз («— и», «— это», «Если X — Y»): {stats['тире_подозрительных_на_1000_слов']}/1000 слов")
    if stats["оборотов_на_1000_слов"] > 15:
        flags.append(f"много причастных/деепричастных оборотов ({stats['оборотов_на_1000_слов']}/1000)")
    if stats["отглаг_сущ_на_100_слов"] > 6:
        flags.append(f"много отглагольных существительных ({stats['отглаг_сущ_на_100_слов']}/100) — канцелярит")
    cv = stats["разброс_длины_предложений_cv"]
    if cv is not None and cv < 0.35:
        flags.append(f"ровный ритм: предложения одной длины (cv={cv})")
    if flags:
        out.append("Флаги: " + "; ".join(flags))
    out.append("")
    order = ["риторика", "синтаксис", "порядок", "подводка", "зачин", "концовка", "калька", "канцелярит", "обороты", "тире", "оформление"]
    for cat in order:
        items = hits.get(cat)
        if not items:
            continue
        out.append(f"## {cat} ({len(items)})")
        for h in items:
            out.append(f"- L{h['line']}: «{re.sub(r'\s+', ' ', h['match'])}» — {h['hint']}\n    …{h['context']}…")
        out.append("")
    return "\n".join(out)


def main(argv):
    as_json = "--json" in argv
    paths = [a for a in argv if a != "--json"] or ["-"]
    results = {}
    for p in paths:
        raw = sys.stdin.read() if p == "-" else open(p, encoding="utf-8").read()
        stats, hits = analyze(raw)
        results[p] = {"stats": stats, "hits": hits}
        if not as_json:
            print(report(p, stats, hits))
    if as_json:
        print(json.dumps(results, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main(sys.argv[1:])
